_ALIASES = {
    "А": "A",
    "В": "B",
    "Е": "E",
    "К": "K",
    "М": "M",
    "Н": "H",
    "О": "O",
    "Р": "P",
    "С": "C",
    "Т": "T",
    "Х": "X",
}


def glyph(char: str) -> list[str]:
    """Returns the 7 rows of a glyph; unknown characters render as ``?``."""
    c = char.upper()
    c = _ALIASES.get(c, c)
    return _GLYPHS.get(c, _GLYPHS["?"]).split(" ")


def render_text(text: str, *, spacing: int = 1, line_spacing: int = 2) -> list[tuple[int, int]]:
    """Returns the ``(column, row)`` cells that are lit for ``text``.

    Rows grow downwards; multiple lines are separated by ``\\n`` and centred
    horizontally.
    """
    lines = text.split("\n")
    widths = [max(0, len(line) * (GLYPH_WIDTH + spacing) - spacing) for line in lines]
    total = max(widths, default=0)
    cells: list[tuple[int, int]] = []
    for li, line in enumerate(lines):
        x0 = (total - widths[li]) // 2
        y0 = li * (GLYPH_HEIGHT + line_spacing)
        for ci, ch in enumerate(line):
            rows = glyph(ch)
            for r, row in enumerate(rows):
                for c, bit in enumerate(row):
                    if bit == "#":
                        cells.append((x0 + ci * (GLYPH_WIDTH + spacing) + c, y0 + r))
    return cells
